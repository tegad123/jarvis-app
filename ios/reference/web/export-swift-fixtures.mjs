#!/usr/bin/env node
// Writes the stub's answers into JarvisKit as PreviewFixtures.swift, so a
// SwiftUI preview and a web reference screenshot show the same rows.
//
//   node ios/reference/web/export-swift-fixtures.mjs
//
// Times are written as placeholders (@@AGO:minutes@@, @@DAY:offset@@,
// "@@TS:seconds@@") that PreviewTransport resolves when a preview runs, so
// "12m" stays "12m" whenever the preview is opened.
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { useClock } from './fixtures.mjs'
import * as routes from './routes.mjs'

useClock({
  ago: (minutes) => `@@AGO:${minutes}@@`,
  day: (offset) => `@@DAY:${offset}@@`,
  secondsAgo: (seconds) => `@@TS:${Math.round(seconds)}@@`,
})

const OUT = fileURLToPath(new URL('../../JarvisKit/Sources/JarvisKit/PreviewFixtures.swift', import.meta.url))

function table(role) {
  const out = {}
  for (const full of routes.paths(role)) {
    const [path, query = ''] = full.split('?')
    const answer = routes.get(path, new URLSearchParams(query), { role, emptyHistory: false })
    if (answer) out[full] = JSON.stringify(answer, null, 1)
  }
  return out
}

function literal(text) {
  if (text.includes('"""#')) throw new Error('fixture text would end the Swift string')
  return `#"""\n${text}\n"""#`
}

function swiftTable(name, doc, entries) {
  const rows = Object.entries(entries)
    .map(([key, value]) => `        ${JSON.stringify(key)}: ${literal(value)},`)
    .join('\n')
  return `    /// ${doc}\n    static let ${name}: [String: String] = [\n${rows}\n    ]\n`
}

const owner = table('owner')
const memberAll = table('member')
const member = Object.fromEntries(Object.entries(memberAll).filter(([key, value]) => owner[key] !== value))
const chat = routes.CHAT_LINES.map((l) => JSON.stringify(l)).join('\n') + '\n'

const swift = `// Generated by ios/reference/web/export-swift-fixtures.mjs from
// ios/reference/web/fixtures.mjs. Do not edit: change the fixtures and run
// the exporter again. Everything here is invented; no tenant, person,
// address, phone number or message is real.

#if DEBUG
enum PreviewFixtures {
${swiftTable('owner', 'GET path (with its query) → JSON, signed in as the owner.', owner)}
${swiftTable('member', 'What a member sees differently.', member)}
    /// The stubbed chat turn, as NDJSON.
    static let chat = ${literal(chat.trimEnd())}
}
#endif
`

await writeFile(OUT, swift)
console.log(`wrote ${OUT}: ${Object.keys(owner).length} owner routes, ${Object.keys(member).length} member overrides`)
