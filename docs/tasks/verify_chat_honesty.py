#!/usr/bin/env python3
"""A chat turn cannot claim a task it did not write.

THREE PATHS, ALL TRIGGERED THROUGH THE REAL SEAM (app.chat._verify_turn), with
the store and the counters read back afterwards:

  1. A REAL CREATION — a row exists, so the person gets a receipt built from
     that row: its title and its id, generated by the server. The model's prose
     is never the confirmation on its own.
  2. A ROUTING MISS — the person asked, nothing was written, the reply makes no
     claim. No success is shown, and the miss is counted so the hit-rate is a
     number rather than an impression.
  3. A FABRICATED CLAIM — the reply says the task was tracked and no row
     exists. The surface shows a correction instead, and intent_claim_unbacked
     increments.

WHY THE THIRD CASE IS FORCED RATHER THAN COAXED. The fabrication is real — it
happened three times on this box — but it is not reproducible on demand, and a
guard that is only tested when the model happens to misbehave is a guard nobody
has tested. So the reply text is supplied directly to the seam. What is under
test is the GUARD, and the guard's input is a string.

Usage:  python3 docs/tasks/verify_chat_honesty.py [-v]
"""

import argparse
import asyncio
import pathlib
import sys

ap = argparse.ArgumentParser()
ap.add_argument("-v", "--verbose", action="store_true")
args = ap.parse_args()

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import env  # noqa: E402

env.apply()
env.reset()

from app import chat as chat_mod, tasks_store, threads as threads_mod  # noqa: E402

ok = []
def ck(name, cond, extra=""):
    ok.append(bool(cond))
    print(f"  {'PASS' if cond else 'FAIL'}  {name}" + (f" — {extra}" if extra else ""))


def counters():
    return {k: v["value"] for k, v in threads_mod.all_counters().items()}


def verify(message, reply, started):
    return asyncio.run(chat_mod._verify_turn("direct", message, reply, started))


print("chat honesty — the row, not the reply, is the truth\n")
ck("this tenant's tasks are verifiable at all", chat_mod._tasks_verifiable())

# ── what counts as asking, and what counts as claiming ───────────────────────
print("\n── reading the two sentences ──────────────────────────────────")
for phrase in ("Track this: call the title company",
               "add a task to chase the survey",
               "remind me to file the returns",
               "put that on my list"):
    ck(f"asking is recognised — {phrase[:34]!r}", bool(chat_mod._TASK_INTENT.search(phrase)))
for phrase in ("What is on my list today?", "Did you track the survey one?"):
    ck(f"a question is NOT an ask — {phrase[:34]!r}",
       not chat_mod._TASK_INTENT.search(phrase))

for phrase in ("I've added that to your list.", "Task created.",
               "That's tracked.", "I tracked it for you."):
    ck(f"a claim is recognised — {phrase[:32]!r}", bool(chat_mod._TASK_CLAIM.search(phrase)))
for phrase in ("I can add that as a task if you like.",
               "Would you like me to track this?",
               "Nothing was added."):
    # An OFFER corrected as a lie would teach the person to ignore corrections.
    ck(f"an offer is NOT a claim — {phrase[:32]!r}",
       not chat_mod._TASK_CLAIM.search(phrase))

# ── 1. a real creation ───────────────────────────────────────────────────────
print("\n── 1. A REAL CREATION — the receipt comes from the row ────────")
before = counters()
started = tasks_store._now()
row = tasks_store.create("Call the title company about 118 Alderwood",
                         created_by="dana", source="chat",
                         source_ref="chat:app:test", assignee="omar")
v = verify("Track this: call the title company about 118 Alderwood",
           "Sure — I'll look into that.", started)
ck("the turn reports success", v is not None and v["ok"] is True, str(v))
ck("the receipt names the task", row["title"] in v["message"], v["message"])
ck("the receipt carries the id, so it can be checked later",
   row["task_id"] in v["message"], v["message"])
ck("   and the id it carries is the one in the store",
   v["task_ids"] == [row["task_id"]], str(v.get("task_ids")))
ck("the receipt is NOT the model's sentence",
   "I'll look into that" not in v["message"])
after = counters()
ck("the ask was counted",
   after.get("chat_task_attempts", 0) == before.get("chat_task_attempts", 0) + 1, str(after))
ck("the creation was counted",
   after.get("chat_task_created", 0) == before.get("chat_task_created", 0) + 1)
ck("nothing was counted as missed",
   after.get("chat_task_missed", 0) == before.get("chat_task_missed", 0))
ck("and nothing was counted as unbacked",
   after.get("intent_claim_unbacked", 0) == before.get("intent_claim_unbacked", 0))

# ── 2. a routing miss ────────────────────────────────────────────────────────
print("\n── 2. A ROUTING MISS — no row, and no success claimed ─────────")
before = counters()
started = tasks_store._now()
v = verify("Track this: order new lockbox batteries",
           "Here is what I found about lockboxes: they typically...", started)
ck("nothing is surfaced as a success", v is None, str(v))
after = counters()
ck("the ask was counted", after.get("chat_task_attempts", 0) == before.get("chat_task_attempts", 0) + 1)
ck("and counted as a MISS — the hit-rate can be computed",
   after.get("chat_task_missed", 0) == before.get("chat_task_missed", 0) + 1, str(after))
ck("no creation was claimed",
   after.get("chat_task_created", 0) == before.get("chat_task_created", 0))
ck("and no unbacked claim was recorded, because none was made",
   after.get("intent_claim_unbacked", 0) == before.get("intent_claim_unbacked", 0))

# ── 3. a fabricated claim ────────────────────────────────────────────────────
print("\n── 3. A FABRICATED CLAIM — corrected, not passed along ────────")
before = counters()
started = tasks_store._now()
# The exact shape the model produced on this box, three times.
FABRICATION = ("Done — I've added that to your list and it's tracked now. "
               "Anything else?")
v = verify("Track this: chase the payoff letter", FABRICATION, started)
ck("the turn refuses to report success", v is not None and v["ok"] is False, str(v))
ck("the correction says plainly that nothing was written",
   "No task was created" in v["message"], v["message"])
ck("   and does not repeat the false claim", "added that to your list" not in v["message"])
ck("   and tells the person what to do instead", "Tasks tab" in v["message"])
ck("no task appeared in the store", not tasks_store.created_since(started))
after = counters()
ck("the fabrication was counted",
   after.get("intent_claim_unbacked", 0) == before.get("intent_claim_unbacked", 0) + 1, str(after))
ck("it also counts as a miss for the hit-rate",
   after.get("chat_task_missed", 0) == before.get("chat_task_missed", 0) + 1)

# ── 4. the guard does not accuse a turn that behaved ─────────────────────────
print("\n── 4. THE GUARD DOES NOT CRY WOLF ─────────────────────────────")
before = counters()
started = tasks_store._now()
r2 = tasks_store.create("Prepare the Kestrel Row packet", created_by="dana",
                        source="chat", source_ref="chat:app:test2")
v = verify("add a task to prepare the Kestrel Row packet",
           "I've added that to your list.", started)
ck("a TRUE claim is confirmed, not corrected", v["ok"] is True, str(v))
ck("   with the real row behind it", r2["task_id"] in v["message"])
after = counters()
ck("a true claim is never counted as unbacked",
   after.get("intent_claim_unbacked", 0) == before.get("intent_claim_unbacked", 0))

started = tasks_store._now()
v = verify("What is on my list?", "You have three open tasks.", started)
ck("an ordinary question produces no receipt and no correction", v is None, str(v))

print(f"\n{sum(ok)}/{len(ok)} passed")
print("counters now: " + ", ".join(
    f"{k}={v}" for k, v in sorted(counters().items())
    if k.startswith(("chat_task", "intent_claim"))))
sys.exit(0 if all(ok) else 1)
